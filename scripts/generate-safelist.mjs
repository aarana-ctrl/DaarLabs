#!/usr/bin/env node
/**
 * Regenerates the safelist block inside src/styles.css.
 *
 * Why this exists: on some machines Tailwind's content scanner finds zero
 * source files (a parent .gitignore, a protected/synced folder, or a symlinked
 * path will do it), so it emits base + theme and no utilities at all — the app
 * renders as unstyled HTML. Listing every candidate token via `@source inline()`
 * makes utility generation independent of filesystem scanning.
 *
 * Scanning stays enabled, so where it works you simply get the union.
 *
 * Run after adding new classes:  npm run safelist
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";

const SRC = "src";
const CSS = "src/styles.css";
const START = "/* SAFELIST:START — generated by scripts/generate-safelist.mjs */";
const END = "/* SAFELIST:END */";

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, out);
    else if ([".tsx", ".ts", ".jsx", ".js"].includes(extname(p))) out.push(p);
  }
  return out;
}

// Mirrors Tailwind's own extractor: any token in the file that could be a utility.
// Parens/commas are matched so tokens containing them are captured whole and then
// discarded — otherwise they'd split into fragments that poison the inline() list.
const CANDIDATE = /[a-zA-Z0-9][a-zA-Z0-9:_\-[\]/.%!<>=@#$&*+(),]*/g;
const tokens = new Set();

const balanced = (t) =>
  (t.match(/\[/g) ?? []).length === (t.match(/\]/g) ?? []).length;

const files = walk(SRC);
for (const file of files) {
  const text = readFileSync(file, "utf8");
  for (const t of text.match(CANDIDATE) ?? []) {
    if (t.length < 2 || t.length > 70) continue;
    if (t.startsWith("http") || t.startsWith("www")) continue;
    if (/["'`(),]/.test(t)) continue; // would break the inline() list
    if (!balanced(t)) continue; // unbalanced brackets break the parser
    tokens.add(t);
  }
}

const list = [...tokens].sort().join(" ");
const block = `${START}\n@source inline("${list}");\n${END}`;

let css = readFileSync(CSS, "utf8");
if (css.includes(START)) {
  css = css.replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`), block);
} else {
  css = css.replace(/(@import "tw-animate-css";\n)/, `$1\n${block}\n`);
}
writeFileSync(CSS, css);

function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
}

console.log(`safelist: ${tokens.size} tokens from ${files.length} files -> ${CSS}`);
